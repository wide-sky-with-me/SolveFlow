function id(value: number): string { return `00000000-0000-4000-8000-${value.toString(16).padStart(12, '0')}`; }
const metadata: ExportTaskMetadata = { batchId: id(1), title: 'Synthetic export', mode: 'answers', layout: 'saved', copies: 1, questionCount: 2 };
const artifact: ExportArtifact = { name: 'export.pdf', mimeType: 'application/pdf', data: new Uint8Array([1, 2, 3]) };
const time = '2026-10-14T00:00:00.000Z';
function task(value: number, patch: Partial<ExportTask> = {}): ExportTask {
  return ExportTaskSchema.parse({ ...metadata, parentId: null, schemaVersion: 1, id: id(value), createdAt: time, startedAt: null, finishedAt: null, status: 'queued', progress: '', error: null, file: null, ...patch });
}
function deferred<T>() {
  let resolve!: (value: T) => void;
  let reject!: (error: unknown) => void;
  const promise = new Promise<T>((yes, no) => { resolve = yes; reject = no; });
  return { promise, resolve, reject };
}
interface Hooks {
  beforeSave?: (value: ExportTask) => Promise<void>;
  afterSave?: (value: ExportTask) => Promise<void>;
  beforeFile?: (key: string, value: ExportArtifact) => Promise<void>;
  afterFile?: (key: string, value: ExportArtifact) => Promise<void>;
  beforeRemoveFile?: (key: string) => Promise<void>;
  beforeRemove?: (key: string) => Promise<void>;
}
function setup(initial: ExportTask[] = [], now: () => Date = () => new Date(time)) {
  const records = new Map(initial.map(value => [value.id, value]));
  const files = new Map<string, ExportArtifact>();
  const hooks: Hooks = {};
  const events: string[] = [];
  const store: LocalExportTaskStore = {
    list: vi.fn(async () => [...records.values()]),
    async save(value) {
      await hooks.beforeSave?.(value); records.set(value.id, structuredClone(value)); events.push(`save:${value.status}`); await hooks.afterSave?.(value);
    },
    async remove(key) { await hooks.beforeRemoveFile?.(key); await hooks.beforeRemove?.(key); records.delete(key); files.delete(key); events.push('remove'); },
    writeFile: vi.fn(async (key, value) => {
      await hooks.beforeFile?.(key, value); files.set(key, { ...value, data: value.data.slice() }); events.push('file'); await hooks.afterFile?.(key, value);
    }),
    readFile: vi.fn(async key => files.get(key) ?? null),
    async removeFile(key) { await hooks.beforeRemoveFile?.(key); files.delete(key); events.push('removeFile'); },
  };
  let sequence = 1000;
  const settled: ExportTaskSnapshot[] = [];
  const queue = new LocalExportTasks({ store, uuid: () => id(sequence++), now, onSettled: value => { settled.push(value); events.push(`notify:${value.status}`); } });
  return { queue, store, records, files, hooks, settled, events };
}
function status(queue: LocalExportTasks, key: string) { return queue.getSnapshot().find(value => value.id === key)?.status; }

describe('generated export recovery', () => {
  it.each(['capacity', 'quota', 'timeout', 'clone', 'unavailable', 'integrity'] as const)('reports the safe %s storage cause and updates it on a failed retry', async reason => {
    const { queue, hooks } = setup(); await queue.initialize();
    const failure = new ExportTaskStorageError(reason); failure.message = 'SECRET_BROWSER_DETAIL';
    hooks.beforeFile = async () => { throw failure; };
    const accepted = await queue.enqueue(metadata, async () => artifact); await queue.waitForIdle();
    expect(queue.getSnapshot()[0]?.error).toBe(new ExportTaskStorageError(reason).message);
    await expect(queue.retrySave(accepted.id)).rejects.toThrow(new ExportTaskStorageError(reason).message);
    hooks.beforeFile = async () => { throw new ExportTaskStorageError('timeout'); };
    await expect(queue.retrySave(accepted.id)).rejects.toThrow(new ExportTaskStorageError('timeout').message);
    expect(queue.getSnapshot()[0]?.error).not.toContain('SECRET'); expect(queue.pendingFileIds).toEqual([accepted.id]);
  });

  it.each(['file', 'metadata'] as const)('reads owned generated bytes after a %s save failure without replaying or claiming success', async phase => {
    const { queue, hooks, store, files, records, settled } = setup(); await queue.initialize();
    if (phase === 'file') hooks.beforeFile = async () => { throw new Error('PRIVATE_QUOTA_DETAIL'); };
    else hooks.beforeSave = async value => { if (value.status === 'succeeded') throw new Error('PRIVATE_METADATA_DETAIL'); };
    const output = { ...artifact, data: artifact.data.slice() }; const runner = vi.fn(async () => output);
    const accepted = await queue.enqueue(metadata, runner); await queue.waitForIdle(); output.data.fill(99);
    expect(queue.pendingFileIds).toEqual([accepted.id]); expect(Object.isFrozen(queue.pendingFileIds)).toBe(true);
    const file = await queue.readPendingFile(accepted.id); expect(file).toEqual(artifact); file?.data.fill(55);
    expect(await queue.readPendingFile(accepted.id)).toEqual(artifact); expect(await queue.readFile(accepted.id)).toBeNull();
    expect(store.readFile).not.toHaveBeenCalled(); expect(status(queue, accepted.id)).toBe('running');
    expect(records.get(accepted.id)?.status).toBe('running'); expect(queue.storageBlocked).toBe(true); expect(settled).toEqual([]);
    delete hooks.beforeFile; delete hooks.beforeSave; await queue.retrySave(accepted.id);
    expect(files.get(accepted.id)).toEqual(artifact); expect(status(queue, accepted.id)).toBe('succeeded');
    expect(queue.pendingFileIds).toEqual([]); expect(await queue.readPendingFile(accepted.id)).toBeNull();
    expect(runner).toHaveBeenCalledTimes(1); expect(settled).toHaveLength(1);
  });

  it('does not expose a generated file once cancellation has been requested, including a read waiting for the lock', async () => {
    const { queue, hooks, store } = setup(); await queue.initialize();
    hooks.beforeFile = async () => { throw new Error('QUOTA'); };
    const accepted = await queue.enqueue(metadata, async () => artifact); await queue.waitForIdle();
    const entered = deferred<void>(); const release = deferred<void>();
    vi.mocked(store.list).mockImplementation(async () => { entered.resolve(); await release.promise; throw new Error('READ_FAILED'); });
    const retry = queue.retrySave(accepted.id).catch(() => undefined); await entered.promise;
    const read = queue.readPendingFile(accepted.id); const cancellation = queue.cancel(accepted.id);
    expect(queue.pendingFileIds).toEqual([]); release.resolve();
    await retry; expect(await read).toBeNull(); await cancellation;
    expect(await queue.readPendingFile(accepted.id)).toBeNull(); expect(status(queue, accepted.id)).toBe('cancelled');
  });

  it('has no generated file to download when a runner fails and only terminal metadata needs saving', async () => {
    const { queue, hooks } = setup(); await queue.initialize();
    hooks.beforeSave = async value => { if (value.status === 'failed') throw new Error('METADATA'); };
    const accepted = await queue.enqueue(metadata, async () => { throw new ExportTaskFailure('合成导出失败'); }); await queue.waitForIdle();
    expect(queue.pendingSaveIds).toEqual([accepted.id]); expect(queue.pendingFileIds).toEqual([]);
    expect(await queue.readPendingFile(accepted.id)).toBeNull(); expect(await queue.readPendingFile(id(9999))).toBeNull();
  });
});

